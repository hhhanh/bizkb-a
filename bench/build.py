"""Build the large-scale benchmark: an expanded agent population and a labelled request set.

Gold labels come from the *generator's intent* (each request is built to be clean or to trip a
specific norm), not from re-running the system under test.

  python -m bench.build            # writes bench/bench_agents.ttl and bench/requests.json
"""
from __future__ import annotations

import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
SEED = 20260919

GOV_TASKS = {  # task: (authority or None, data class, needs-plugin-provider)
    "RegisterBirth": ("CivilRegistryAuthority", "PersonalData"),
    "RegisterPermanentResidence": ("ResidenceAuthority", "PersonalData"),
    "IssueChildHealthInsurance": ("SocialInsuranceAuthority", "PersonalData"),
    "NotifyCitizen": (None, "PublicData"),
}
COM_TASKS = {
    "SearchOffers": (None, "PublicData"),
    "VerifyMerchant": (None, "PublicData"),
    "RetrieveOrderHistory": (None, "PersonalData"),
    "ObtainPaymentMandate": (None, "FinancialData"),
    "ExecutePayment": ("PaymentLicense", "FinancialData"),
    "ArrangeDelivery": (None, "PersonalData"),
    "ArrangeReturnPickup": (None, "PersonalData"),
    "ExecuteRefund": ("PaymentLicense", "FinancialData"),
    "IssueEInvoice": ("EInvoiceProvider", "FinancialData"),
}
EXTRA_DC = {"ExecutePayment": ["PublicData"], "IssueEInvoice": ["PersonalData"]}


def build_agents() -> tuple[str, dict]:
    rnd = random.Random(SEED)
    lines = ["@prefix bka: <https://ndta.gov.vn/ns/bizkb-a#> .",
             "@prefix gov: <https://ndta.gov.vn/ns/govtech#> .",
             "@prefix com: <https://ndta.gov.vn/ns/acommerce#> .",
             "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
             "# Generated by bench/build.py — expanded agent population for the benchmark", ""]
    meta = {}

    def emit(aid, ns, dom, provides, auth, dcs, trust, cost, attested, trap):
        iss = "bka:issuer_ndta" if ns == "gov" else "com:issuer_ecom"
        body = [f"{ns}:{aid} a bka:Agent ; rdfs:label \"{aid}\" ;",
                f"  bka:provides {', '.join(f'{ns}:{p}' for p in provides)} ;",
                f"  bka:inDomain {'gov:GovDomain' if ns == 'gov' else 'com:CommerceDomain'} ;",
                f"  bka:handlesDataClass {', '.join('bka:' + d for d in dcs)} ;",
                f"  bka:trust {trust} ; bka:cost {cost} ; bka:protocol \"local\""]
        if auth:
            body.append(f"  ; bka:hasAuthority {'gov:' if ns == 'gov' else 'com:'}{auth}")
        if attested:
            body.append(f"  ; bka:attestedBy {iss}")
        lines.append("\n".join(body) + " .")
        meta[f"{ns}_{aid}"] = {"id": aid, "domain": ns, "provides": provides, "auth": auth,
                               "dc": dcs, "attested": attested, "trap": trap}

    for ns, tasks in (("gov", GOV_TASKS), ("com", COM_TASKS)):
        for task, (auth, dc) in tasks.items():
            dcs = [dc] + EXTRA_DC.get(task, [])
            emit(f"bx_{task}_prime", ns, ns, [task], auth, dcs, round(rnd.uniform(.88, .95), 2),
                 round(rnd.uniform(.28, .42), 2), True, False)
            if rnd.random() < .7:      # a second compliant provider, cheaper: real competition
                emit(f"bx_{task}_alt", ns, ns, [task], auth, dcs, round(rnd.uniform(.80, .88), 2),
                     round(rnd.uniform(.12, .26), 2), True, False)
            kind = rnd.choice(["unattested", "noauth", "nodata"] if auth else ["unattested", "nodata"])
            if kind == "unattested":   # claims everything, signed by nobody
                emit(f"bx_{task}_trap_unattested", ns, ns, [task], auth, dcs, .98, .02, False, True)
            elif kind == "noauth":     # attested but not licensed for this act
                emit(f"bx_{task}_trap_noauth", ns, ns, [task], None, dcs, .95, .05, True, True)
            else:                      # attested and licensed but not cleared for the data class
                emit(f"bx_{task}_trap_nodata", ns, ns, [task], auth, ["PublicData"], .93, .03, True, True)
    # a provider advertising the more general capability (plug-in degree)
    emit("bx_generic_insurance", "gov", "gov", ["IssueHealthInsuranceCard"], "SocialInsuranceAuthority",
         ["PersonalData"], .9, .33, True, False)
    return "\n".join(lines) + "\n", meta


PHRASES = {
    "BirthLifeEvent": ["đăng ký khai sinh cho con", "tôi muốn đăng ký khai sinh", "làm khai sinh cho bé",
                       "khai sinh cho con mới sinh", "register a birth", "I need to register my baby",
                       "birth registration for my newborn", "register my baby please"],
    "PurchaseGoods": ["đặt mua {p}", "tôi muốn mua hàng {p}", "mua hàng giúp tôi: {p}", "đặt mua ngay {p}",
                      "order {p}", "buy {p} for me", "purchase {p}", "please order {p}"],
    "DelegatedPurchase": ["tự động mua {p} khi giá tốt", "tự động đặt {p} giúp tôi", "mua giúp khi {p} giảm giá",
                          "tự động mua {p}", "automatically buy {p}", "auto-buy {p} when cheap",
                          "delegated purchase of {p}", "buy when {p} drops in price"],
    "ReturnAndRefund": ["tôi muốn trả hàng", "trả hàng và hoàn tiền đơn vừa rồi", "hoàn tiền cho tôi",
                        "trả hàng đơn hôm qua", "return my order", "refund my last order",
                        "I want a refund", "return and refund please"],
    "ReorderLastPurchase": ["mua lại đơn hàng trước", "đặt lại đơn cũ", "mua lại giúp tôi", "mua lại đơn tuần trước",
                            "reorder my previous purchase", "buy again what I bought", "reorder please",
                            "same order again"],
}
PRODUCTS = ["sữa công thức", "gạo ST25", "nước rửa tay", "infant formula", "rice", "hand soap"]
OUT_OF_SCOPE = ["xin cấp giấy phép xây dựng", "tra cứu điểm thi của con", "đăng ký kết hôn",
                "xin visa đi Hàn Quốc", "đặt lịch khám bệnh", "nộp thuế thu nhập cá nhân",
                "apply for a building permit", "book a doctor appointment", "file my income tax",
                "renew my driving licence", "check exam results", "apply for a visa",
                "đăng ký thường trú cho người nước ngoài", "tra cứu bảo hiểm thất nghiệp", "mở tài khoản ngân hàng"]

CASES = [  # (case id, expected decision, expected norm codes, context builder key)
    ("clean", "accept", []), ("over_cap", "reject", ["C2"]), ("wrong_cat", "reject", ["C3"]),
    ("expired", "reject", ["C4"]), ("no_mandate", "reject", ["C7", "N4"]), ("unverified", "reject", ["C1"]),
    ("prohibited", "reject", ["C5"]), ("cross_border", "accept", []),
]


def ctx_for(case: str, goal: str, rnd: random.Random) -> dict | None:
    if goal == "BirthLifeEvent":
        return None
    base = {"amount": rnd.choice([150_000, 300_000, 420_000]), "merchant": "merchant_A",
            "category": "Groceries", "mandate": None}
    mand = {"cap": 500_000, "days": 30, "cats": ["Groceries"]}
    if goal == "DelegatedPurchase" and case not in ("no_mandate",):
        base["mandate"] = dict(mand)
    if case == "over_cap":
        base["amount"] = rnd.choice([700_000, 900_000, 1_200_000])
    elif case == "wrong_cat":
        base["category"] = "Electronics"
    elif case == "expired":
        base["mandate"] = dict(mand, days=-rnd.randint(1, 60))
    elif case == "no_mandate":
        base["mandate"] = None
    elif case == "unverified":
        base["merchant"] = "merchant_B"
    elif case == "prohibited":
        base["category"] = "PrescriptionDrugs"
    elif case == "cross_border":
        base["merchant"] = "merchant_X"
    return base


def build_requests(n_total: int = 300, out_share: float = .15) -> list[dict]:
    rnd = random.Random(SEED)
    out_n = int(n_total * out_share)
    in_n = n_total - out_n
    plan = []          # (goal, case) draws
    gov_n = 60
    plan += [("BirthLifeEvent", "clean")] * gov_n
    com_goals = ["PurchaseGoods", "DelegatedPurchase", "ReturnAndRefund", "ReorderLastPurchase"]
    remaining = in_n - gov_n
    cases_by_goal = {
        "PurchaseGoods": ["clean", "clean", "unverified", "prohibited", "cross_border"],
        "DelegatedPurchase": ["clean", "over_cap", "wrong_cat", "expired", "no_mandate", "cross_border"],
        "ReturnAndRefund": ["clean"], "ReorderLastPurchase": ["clean", "unverified"],
    }
    pool = [(g, c) for g in com_goals for c in cases_by_goal[g]]
    while len(plan) < in_n:
        plan.append(pool[(len(plan) - gov_n) % len(pool)])
    reqs = []
    for i, (goal, case) in enumerate(plan):
        phr = PHRASES[goal][i % len(PHRASES[goal])]
        product = rnd.choice(PRODUCTS)
        text = phr.format(p=product) if "{p}" in phr else phr
        ctx = ctx_for(case, goal, rnd)
        decision, codes = next((d, c) for k, d, c in CASES if k == case)
        if case == "cross_border":
            decision, codes = "accept", []
        reqs.append({"id": f"R{i:03d}", "text": text, "goal": goal, "case": case, "ctx": ctx,
                     "gold_decision": decision, "gold_codes": codes,
                     "gold_hitl": bool(goal in ("PurchaseGoods", "ReorderLastPurchase")
                                       or case == "cross_border" or case == "no_mandate")})
    for j in range(out_n):
        reqs.append({"id": f"X{j:03d}", "text": OUT_OF_SCOPE[j % len(OUT_OF_SCOPE)], "goal": None,
                     "case": "out_of_scope", "ctx": None, "gold_decision": "refuse", "gold_codes": [],
                     "gold_hitl": False})
    rnd.shuffle(reqs)
    return reqs


if __name__ == "__main__":
    ttl, meta = build_agents()
    (HERE / "bench_agents.ttl").write_text(ttl, encoding="utf-8")
    reqs = build_requests()
    (HERE / "requests.json").write_text(json.dumps(reqs, ensure_ascii=False, indent=1), encoding="utf-8")
    traps = sum(1 for m in meta.values() if m["trap"])
    print(f"agents generated: {len(meta)} (traps {traps}, {traps / len(meta):.0%})")
    from collections import Counter
    print("requests:", len(reqs), Counter(r["case"] for r in reqs))
